CREATE TABLE investment_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    birth_date DATE NOT NULL,
    monthly_income BIGINT NOT NULL,
    monthly_fixed_expense BIGINT NOT NULL,
    monthly_variable_expense BIGINT NOT NULL,
    irregular_expense_reserve BIGINT NOT NULL,
    emergency_fund_contribution BIGINT NOT NULL,
    monthly_debt_repayment BIGINT NOT NULL,
    current_cash BIGINT NOT NULL,
    goal_amount BIGINT NOT NULL,
    goal_months INTEGER NOT NULL,
    selected_scenario VARCHAR(20),
    selected_product_id VARCHAR(50),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_investment_plans_member UNIQUE (member_id),
    CONSTRAINT fk_investment_plans_member FOREIGN KEY (member_id) REFERENCES members (id)
);
