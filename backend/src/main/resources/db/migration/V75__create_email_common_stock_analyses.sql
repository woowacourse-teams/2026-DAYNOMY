CREATE TABLE email_common_stock_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES assets (id),
    asset_code VARCHAR(50) NOT NULL,
    market VARCHAR(20) NOT NULL,
    category VARCHAR(30) NOT NULL,
    model VARCHAR(100) NOT NULL,
    analysis_version VARCHAR(100) NOT NULL,
    evidence_version VARCHAR(100) NOT NULL,
    as_of TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    content JSONB NOT NULL,
    content_hash VARCHAR(64) NOT NULL CHECK (content_hash ~ '^[a-f0-9]{64}$'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    analyzed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    verification JSONB,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_email_common_stock_analyses_key
        UNIQUE (asset_id, model, analysis_version, evidence_version, as_of),
    CONSTRAINT ck_email_common_stock_analyses_time CHECK (as_of <= analyzed_at),
    CONSTRAINT ck_email_common_stock_analyses_verification
        CHECK ((status = 'PENDING' AND verification IS NULL)
            OR (status IN ('VERIFIED', 'REJECTED') AND verification IS NOT NULL))
);
