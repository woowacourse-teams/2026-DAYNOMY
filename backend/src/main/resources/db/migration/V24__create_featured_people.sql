CREATE TABLE featured_people (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    x_profile_url TEXT,
    threads_profile_url TEXT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_featured_people_name UNIQUE (name)
);

CREATE TABLE featured_person_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    title VARCHAR(255) NOT NULL,
    url TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_featured_person_posts_person
        FOREIGN KEY (person_id) REFERENCES featured_people (id) ON DELETE CASCADE,
    CONSTRAINT uk_featured_person_posts_person_url UNIQUE (person_id, url)
);

CREATE INDEX idx_featured_person_posts_person_created
    ON featured_person_posts (person_id, created_at DESC, id DESC);
