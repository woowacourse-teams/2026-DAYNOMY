CREATE TABLE news_generation_topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_key VARCHAR(64) NOT NULL,
    generation_type VARCHAR(20) NOT NULL,
    title VARCHAR(255) NOT NULL,
    reference_date DATE NOT NULL,
    category VARCHAR(30) NOT NULL,
    facts JSONB NOT NULL,
    sources JSONB NOT NULL,
    status VARCHAR(20) NOT NULL,
    reservation_token UUID,
    reserved_at TIMESTAMP(6) WITH TIME ZONE,
    news_id BIGINT UNIQUE REFERENCES news (id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_news_generation_topics_topic_key UNIQUE (topic_key),
    CONSTRAINT ck_news_generation_topics_type
        CHECK (generation_type IN ('KOREA', 'US')),
    CONSTRAINT ck_news_generation_topics_status
        CHECK (status IN ('READY', 'RESERVED', 'GENERATED')),
    CONSTRAINT ck_news_generation_topics_reservation
        CHECK (
            (status = 'RESERVED' AND reservation_token IS NOT NULL AND reserved_at IS NOT NULL)
            OR
            (status <> 'RESERVED' AND reservation_token IS NULL AND reserved_at IS NULL)
        ),
    CONSTRAINT ck_news_generation_topics_facts
        CHECK (jsonb_typeof(facts) = 'array' AND jsonb_array_length(facts) >= 3),
    CONSTRAINT ck_news_generation_topics_sources
        CHECK (jsonb_typeof(sources) = 'array' AND jsonb_array_length(sources) BETWEEN 2 AND 4),
    CONSTRAINT ck_news_generation_topics_news
        CHECK ((status = 'GENERATED' AND news_id IS NOT NULL)
            OR (status <> 'GENERATED' AND news_id IS NULL))
);

CREATE INDEX idx_news_generation_topics_ready
    ON news_generation_topics (generation_type, status, reference_date, id);

CREATE INDEX idx_news_generation_topics_recent
    ON news_generation_topics (generation_type, reference_date DESC, id DESC);
