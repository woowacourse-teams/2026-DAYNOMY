CREATE TABLE portfolio_analysis_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    analysis_id BIGINT,
    question VARCHAR(200) NOT NULL CHECK (char_length(question) BETWEEN 10 AND 200),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    snapshot JSONB NOT NULL CHECK (jsonb_typeof(snapshot) = 'object'),
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE(owner_member_id, analysis_id)
);

CREATE INDEX idx_portfolio_analysis_shares_owner_created
    ON portfolio_analysis_shares(owner_member_id, created_at DESC, id DESC);

CREATE TABLE portfolio_analysis_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_id BIGINT NOT NULL REFERENCES portfolio_analysis_shares(id) ON DELETE CASCADE,
    author_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    parent_comment_id BIGINT REFERENCES portfolio_analysis_comments(id) ON DELETE CASCADE,
    content TEXT NOT NULL CHECK (char_length(content) BETWEEN 2 AND 1000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_portfolio_analysis_comments_share_created
    ON portfolio_analysis_comments(share_id, created_at, id);

CREATE INDEX idx_portfolio_analysis_comments_parent_created
    ON portfolio_analysis_comments(parent_comment_id, created_at, id);
