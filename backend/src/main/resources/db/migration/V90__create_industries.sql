CREATE TABLE industries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(50) NOT NULL,
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_industries_code UNIQUE (code),
    CONSTRAINT ck_industries_display_order_non_negative CHECK (display_order >= 0)
);

CREATE TABLE asset_industries (
    asset_id BIGINT NOT NULL,
    industry_id BIGINT NOT NULL,
    CONSTRAINT pk_asset_industries PRIMARY KEY (asset_id, industry_id),
    CONSTRAINT fk_asset_industries_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT fk_asset_industries_industry FOREIGN KEY (industry_id) REFERENCES industries (id)
);

CREATE INDEX idx_asset_industries_industry_asset
    ON asset_industries (industry_id, asset_id);

