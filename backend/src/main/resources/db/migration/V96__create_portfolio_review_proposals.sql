CREATE TABLE portfolio_review_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_id BIGINT NOT NULL REFERENCES portfolio_analysis_shares(id) ON DELETE CASCADE,
    comment_id BIGINT NOT NULL UNIQUE REFERENCES portfolio_analysis_comments(id) ON DELETE CASCADE,
    snapshot JSONB NOT NULL CHECK (jsonb_typeof(snapshot) = 'object'),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_portfolio_review_proposals_share_updated
    ON portfolio_review_proposals(share_id, updated_at DESC, id DESC);
