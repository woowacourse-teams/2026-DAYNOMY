CREATE TABLE portfolio_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios (id) ON DELETE CASCADE,
    previous_analysis_id BIGINT REFERENCES portfolio_analyses (id) ON DELETE SET NULL,
    schema_version INTEGER NOT NULL CHECK (schema_version > 0),
    analysis_version VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    snapshot JSONB NOT NULL CHECK (jsonb_typeof(snapshot) = 'object'),
    analyzed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    change_reason TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_portfolio_analyses_portfolio_analyzed
    ON portfolio_analyses (portfolio_id, analyzed_at DESC, id DESC);

CREATE TABLE portfolio_analysis_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT NOT NULL REFERENCES portfolio_analyses (id) ON DELETE CASCADE,
    asset_name VARCHAR(100) NOT NULL,
    title TEXT NOT NULL,
    url TEXT NOT NULL,
    published_on DATE,
    occurred_on DATE,
    excerpt TEXT NOT NULL
);

CREATE INDEX idx_portfolio_analysis_evidence_analysis
    ON portfolio_analysis_evidence (analysis_id);

-- 재확인마다 이력을 쌓지 않고 최근 성공/실패 상태만 보관한다.
CREATE TABLE portfolio_analysis_checks (
    portfolio_id BIGINT PRIMARY KEY REFERENCES portfolios (id) ON DELETE CASCADE,
    last_succeeded_at TIMESTAMP(6) WITH TIME ZONE,
    last_failed_at TIMESTAMP(6) WITH TIME ZONE,
    failure_code VARCHAR(100),
    CONSTRAINT ck_portfolio_analysis_checks_failure
        CHECK ((last_failed_at IS NULL) = (failure_code IS NULL))
);
