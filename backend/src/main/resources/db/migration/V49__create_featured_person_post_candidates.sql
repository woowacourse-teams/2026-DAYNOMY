CREATE TABLE featured_person_post_candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    title VARCHAR(255) NOT NULL,
    url TEXT NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    status VARCHAR(20) NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_featured_person_post_candidates_person
        FOREIGN KEY (person_id) REFERENCES featured_people (id) ON DELETE CASCADE,
    CONSTRAINT uk_featured_person_post_candidates_person_url UNIQUE (person_id, url)
);

CREATE INDEX idx_featured_person_post_candidates_person_status_created
    ON featured_person_post_candidates (person_id, status, created_at DESC, id DESC);
