INSERT INTO market_trading_days(base_date, trading)
SELECT d::date, EXTRACT(ISODOW FROM d) < 6 AND d::date NOT IN (DATE '2026-01-01', DATE '2026-02-16', DATE '2026-02-17', DATE '2026-02-18', DATE '2026-03-02', DATE '2026-05-01', DATE '2026-05-05', DATE '2026-05-25', DATE '2026-06-03', DATE '2026-07-17', DATE '2026-08-17', DATE '2026-09-24', DATE '2026-09-25', DATE '2026-10-05', DATE '2026-10-09', DATE '2026-12-25', DATE '2026-12-31')
FROM generate_series(DATE '2026-01-01', DATE '2026-12-31', INTERVAL '1 day') AS d;
