-- 최초로 남아 있는 성과 기준일을 보존한다. 삭제된 과거 신청 시각은 추정하지 않는다.
UPDATE public_investor_profiles p SET tracking_started_on = (
 SELECT MIN(r.base_date) FROM portfolio_daily_returns r
 JOIN shared_portfolios s ON s.id = r.portfolio_id
 WHERE s.member_id = p.member_id AND r.eligible
);
CREATE TABLE league_participations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id BIGINT NOT NULL REFERENCES public_investor_profiles(id) ON DELETE CASCADE,
 started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 ended_at TIMESTAMP(6) WITH TIME ZONE,
 CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE UNIQUE INDEX uk_league_open_participation ON league_participations(profile_id) WHERE ended_at IS NULL;
INSERT INTO league_participations(profile_id, started_at)
SELECT id, league_enabled_at FROM public_investor_profiles WHERE league_enabled AND league_enabled_at IS NOT NULL;
CREATE TABLE market_trading_days (
 base_date DATE PRIMARY KEY,
