CREATE TABLE pmf_survey_visitors (
    respondent_key VARCHAR(48) PRIMARY KEY,
    first_observed_at TIMESTAMPTZ NOT NULL,
    first_visit_session VARCHAR(64) NOT NULL,
    last_analysis_request_at TIMESTAMPTZ
);

CREATE TABLE pmf_survey_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id BIGINT NOT NULL CHECK (survey_id > 0),
    respondent_key VARCHAR(48) NOT NULL REFERENCES pmf_survey_visitors (respondent_key),
    answer VARCHAR(24) NOT NULL CHECK (answer IN (
        'VERY_DISAPPOINTED', 'SOMEWHAT_DISAPPOINTED', 'NOT_DISAPPOINTED', 'NO_LONGER_USING'
    )),
    reason VARCHAR(500),
    responded_at TIMESTAMPTZ NOT NULL,
    source VARCHAR(16) NOT NULL CHECK (source = 'IN_APP'),
    cohort VARCHAR(24) NOT NULL CHECK (cohort IN ('OFFICIAL_PMF', 'OTHER', 'HISTORY_UNKNOWN')),
    analysis_request_at TIMESTAMPTZ,
    UNIQUE (survey_id, respondent_key)
);

CREATE TABLE pmf_survey_snoozes (
    survey_id BIGINT NOT NULL CHECK (survey_id > 0),
    respondent_key VARCHAR(48) NOT NULL REFERENCES pmf_survey_visitors (respondent_key),
    hidden_until TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (survey_id, respondent_key)
);
