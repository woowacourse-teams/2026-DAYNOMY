CREATE TABLE portfolio_asset_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_name VARCHAR(100) NOT NULL,
    analysis_version VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    snapshot JSONB NOT NULL,
    analyzed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_portfolio_asset_analyses_key UNIQUE (asset_name, analysis_version, model),
    CONSTRAINT ck_portfolio_asset_analyses_expiry CHECK (expires_at > analyzed_at)
);
