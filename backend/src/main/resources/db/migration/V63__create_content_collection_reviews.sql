CREATE TABLE collected_external_content_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collected_content_id BIGINT NOT NULL,
    suggested_asset_id BIGINT,
    status VARCHAR(20) NOT NULL,
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_collected_content_reviews_content
        FOREIGN KEY (collected_content_id) REFERENCES collected_external_contents (id),
    CONSTRAINT fk_collected_content_reviews_asset
        FOREIGN KEY (suggested_asset_id) REFERENCES assets (id),
    CONSTRAINT ck_collected_content_reviews_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE UNIQUE INDEX uk_collected_content_reviews_content_asset
    ON collected_external_content_reviews (collected_content_id, suggested_asset_id)
    WHERE suggested_asset_id IS NOT NULL;

CREATE UNIQUE INDEX uk_collected_content_reviews_unmatched
    ON collected_external_content_reviews (collected_content_id)
    WHERE suggested_asset_id IS NULL;

CREATE INDEX idx_collected_content_reviews_status_created
    ON collected_external_content_reviews (status, created_at DESC, id DESC);

INSERT INTO collected_external_content_reviews (
    collected_content_id, suggested_asset_id, status, reviewed_at, created_at, updated_at)
SELECT DISTINCT ON (collected.id, related.asset_id)
    collected.id,
    related.asset_id,
    'APPROVED',
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
FROM collected_external_contents collected
JOIN stock_related_contents related ON related.url = collected.url
ORDER BY collected.id, related.asset_id;

INSERT INTO collected_external_content_reviews (
    collected_content_id, suggested_asset_id, status, reviewed_at, created_at, updated_at)
SELECT collected.id, NULL, 'PENDING', NULL, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM collected_external_contents collected
WHERE NOT EXISTS (
    SELECT 1
    FROM collected_external_content_reviews review
    WHERE review.collected_content_id = collected.id
);
