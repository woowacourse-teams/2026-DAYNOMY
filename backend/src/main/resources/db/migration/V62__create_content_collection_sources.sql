CREATE TABLE content_collection_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    source_url TEXT NOT NULL,
    asset_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_collected_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_content_collection_sources_asset
        FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT uk_content_collection_sources_type_url UNIQUE (source_type, source_url),
    CONSTRAINT ck_content_collection_sources_type
        CHECK (source_type IN ('YOUTUBE', 'THREADS', 'X'))
);

CREATE INDEX idx_content_collection_sources_enabled_id
    ON content_collection_sources (enabled, id);

CREATE TABLE collected_external_contents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    url TEXT NOT NULL,
    image_url TEXT,
    published_date DATE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_collected_external_contents_source
        FOREIGN KEY (source_id) REFERENCES content_collection_sources (id),
    CONSTRAINT uk_collected_external_contents_url UNIQUE (url)
);

CREATE INDEX idx_collected_external_contents_source_published
    ON collected_external_contents (source_id, published_date DESC, id DESC);
